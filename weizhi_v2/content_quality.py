def apply_depth(card):
    item = DEPTH.get(card.get("concept_id"))
    if not item:
        return card
    content = card.setdefault("content", {})
    existing = {section.get("heading") for section in content.get("sections") or []}
    additions = [
        {"heading": "4. 具体推演", "paragraphs": item[0]},
        {"heading": "5. 边界与迁移", "paragraphs": item[1]},
    ]
    content.setdefault("sections", []).extend(section for section in additions if section["heading"] not in existing)
    return card


def learning_character_count(card):
    content = card.get("content") or {}
    parts = [content.get("lead") or ""]
    parts.extend(p for section in content.get("sections") or [] for p in section.get("paragraphs") or [])
    parts.extend(content.get("key_points") or [])
    parts.extend(q.get("explanation") or "" for q in content.get("quiz") or [])
    return sum(len(part.strip()) for part in parts)
