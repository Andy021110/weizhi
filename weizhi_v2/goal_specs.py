def evaluate_goal_spec(spec):
    issues = []
    milestones = spec.get("milestones") or []
    evidence = spec.get("success_evidence") or []
    generic = {"建立基础心智模型", "理解真实材料与系统", "完成迁移应用", "学习相关知识"}
    if not 4 <= len(milestones) <= 5:
        issues.append("里程碑数量应为 4-5")
    if not 3 <= len(evidence) <= 5:
        issues.append("成功证据数量应为 3-5")
    if any((m.get("outcome") or "") in generic for m in milestones):
        issues.append("包含泛化里程碑")
    if any(len(m.get("outcome") or "") < 18 for m in milestones):
        issues.append("里程碑不够具体")
    if any(len(item) < 20 for item in evidence):
        issues.append("成功证据不可充分验证")
    if not 60 <= int(spec.get("daily_minutes") or 0) <= 120:
        issues.append("每日时间不符合产品约束")
    return {"score": max(0, 100 - len(issues) * 15), "issues": issues}
